    <h1>Usuwanie konta</h1>
    <p class="upd">Aplikacja „Ja i Ty" · [nazwa wydawcy]</p>

    <p>Na tej stronie opisujemy, jak usunąć konto w aplikacji „Ja i Ty" i co się wtedy dzieje z Waszymi danymi.</p>

    <h2>Jak usunąć konto w aplikacji</h2>
    <p>Otwórz aplikację i wybierz <strong>Profil → Usuń konto</strong>, a potem potwierdź. Jeśli logujesz się przez Apple, aplikacja poprosi Cię jeszcze o potwierdzenie przez Apple. Dzięki temu możemy poprosić Apple o odłączenie „Ja i Ty" od Twojego Apple ID.</p>

    <h2>Co usuwamy</h2>
    <p>Konto usuwamy od razu i na stałe. Nie ma okresu oczekiwania ani możliwości przywrócenia. Usuwamy:</p>
    <ul>
        <li>dane konta: adres e-mail, nick, hasło, strefę czasową, język i powiązanie z kontem Apple lub Google;</li>
        <li>wszystkie odpowiedzi i wspomnienia, także te usunięte wcześniej;</li>
        <li>historię gry: rozegrane i polubione karty, odblokowane karty, sesje, rytuały tygodnia, serię;</li>
        <li>zdobyte nagrody, kamienie milowe i zrealizowane kody;</li>
        <li>polecenia w obie strony, także te, w których ktoś założył konto z Twojego polecenia;</li>
        <li>tokeny powiadomień i tokeny logowania. Po usunięciu konta aplikacja zostaje wylogowana na każdym urządzeniu.</li>
    </ul>

    <h2>Co może zostać przez pewien czas</h2>
    <ul>
        <li><strong>Wpis o usunięciu konta:</strong> w logach serwera zostaje wpis z wewnętrznym identyfikatorem konta i datą usunięcia, bez adresu e-mail. Dzięki niemu możemy potwierdzić, że konto zostało usunięte.</li>
        <li><strong>Logi serwera</strong> wygasają po [X] dniach.</li>
        <li><strong>Raporty awarii</strong> (nie zawierają treści Waszych odpowiedzi ani wspomnień) wygasają zgodnie z ustawieniami dostawcy, Sentry.</li>
        <li><strong>Kopie zapasowe bazy</strong> są nadpisywane po [Y] dniach.</li>
    </ul>

    <h2>Nie masz dostępu do aplikacji?</h2>
    <p>Napisz na <a href="mailto:kontakt@jaity.app?subject=Usuni%C4%99cie%20konta">kontakt@jaity.app</a> z tematem „Usunięcie konta". Napisz z adresu przypisanego do konta i podaj swój nick z aplikacji. Jeśli logujesz się przez Apple z ukrytym adresem e-mail, sam nick wystarczy, żeby znaleźć konto. Usuniemy je bez zbędnej zwłoki, najpóźniej w ciągu miesiąca, i potwierdzimy to mailowo.</p>

    <p>Więcej o tym, jak przetwarzamy dane: <a href="/privacy">polityka prywatności</a>.</p>

