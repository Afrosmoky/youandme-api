    <h1>Standardy bezpieczeństwa dzieci</h1>
    <p class="upd">Ostatnia aktualizacja: 31 sierpnia 2026</p>

    <p>Aplikacja „Ja i Ty" to gra w pytania przeznaczona wyłącznie dla osób dorosłych będących w związku. Poniżej opisujemy nasze standardy dotyczące przeciwdziałania wykorzystywaniu seksualnemu dzieci i naruszaniu ich praw oraz sposób zgłaszania nam obaw w tym zakresie.</p>

    <h2>Zakaz</h2>
    <p>W aplikacji „Ja i Ty" obowiązuje <strong>bezwzględny zakaz</strong> jakichkolwiek działań związanych z wykorzystywaniem seksualnym dzieci lub naruszaniem ich praw. Dotyczy to w szczególności:</p>
    <ul>
        <li>tworzenia, przechowywania, przesyłania i udostępniania materiałów przedstawiających wykorzystywanie seksualne dzieci;</li>
        <li>wykorzystywania aplikacji do nawiązywania kontaktu z osobami małoletnimi w celach seksualnych;</li>
        <li>wszelkich treści seksualizujących osoby małoletnie lub przedstawiających je w sposób sugerujący takie treści.</li>
    </ul>
    <p>Naruszenie tego zakazu skutkuje natychmiastowym i trwałym zablokowaniem konta oraz zgłoszeniem sprawy właściwym organom ścigania.</p>

    <h2>Aplikacja jest przeznaczona wyłącznie dla dorosłych</h2>
    <p>„Ja i Ty" nie jest kierowana do dzieci ani młodzieży. Zawiera treści dla dorosłych i jest w ten sposób oznaczona w sklepie z aplikacjami. Konto może założyć wyłącznie osoba pełnoletnia. Jeśli poweźmiemy uzasadnione podejrzenie, że konto należy do osoby małoletniej, blokujemy je i usuwamy powiązane z nim dane.</p>

    <h2>Jak zbudowana jest aplikacja</h2>
    <p>Ryzyko wystąpienia opisanych wyżej naruszeń ograniczamy przede wszystkim konstrukcją samej aplikacji:</p>
    <ul>
        <li>aplikacja <strong>nie umożliwia kontaktu między użytkownikami</strong> — nie ma czatu, wiadomości ani profili publicznych;</li>
        <li>aplikacja <strong>nie pozwala przesyłać zdjęć, plików ani nagrań</strong>;</li>
        <li>użytkownicy <strong>nie publikują treści widocznych dla innych</strong> — odpowiedzi i zapisane wspomnienia są dostępne wyłącznie dla danej pary;</li>
        <li>treść pytań pochodzi wyłącznie od zespołu „Ja i Ty" i przed udostępnieniem przechodzi naszą weryfikację redakcyjną;</li>
        <li>gra toczy się na jednym urządzeniu, między dwiema osobami, które znają się osobiście.</li>
    </ul>
    <p>Jeżeli w przyszłości udostępnimy funkcje pozwalające użytkownikom tworzyć treści widoczne dla innych osób lub komunikować się między sobą, wdrożymy odpowiadające im mechanizmy moderacji i zaktualizujemy niniejsze standardy przed uruchomieniem takich funkcji.</p>

    <h2>Jak zgłosić obawy</h2>
    <div class="note">
        Obawy dotyczące bezpieczeństwa dzieci, podejrzenie naruszenia powyższych zasad lub jakąkolwiek niepokojącą treść zgłoś na adres <a href="mailto:kontakt@jaity.app">kontakt@jaity.app</a>. W zgłoszeniu opisz, czego dotyczy sprawa, i podaj — jeśli to możliwe — adres e-mail powiązany z kontem, którego zgłoszenie dotyczy.
    </div>
    <p>Każde zgłoszenie rozpatrujemy niezwłocznie po jego otrzymaniu. Zgłoszenia dotyczące bezpieczeństwa dzieci traktujemy priorytetowo i rozpatrujemy przed pozostałą korespondencją.</p>

    <h2>Co robimy po otrzymaniu zgłoszenia</h2>
    <ul>
        <li>weryfikujemy zgłoszenie i zabezpieczamy związane z nim dane;</li>
        <li>blokujemy konto, którego dotyczy zgłoszenie, jeśli podejrzenie okaże się uzasadnione;</li>
        <li>zawiadamiamy właściwe organy ścigania i przekazujemy im informacje niezbędne do prowadzenia postępowania;</li>
        <li>informujemy osobę zgłaszającą o zakończeniu rozpatrywania sprawy, o ile podała dane kontaktowe.</li>
    </ul>

    <h2>Zgodność z prawem i zgłaszanie organom</h2>
    <p>Działamy zgodnie z przepisami prawa polskiego i prawa Unii Europejskiej dotyczącymi ochrony dzieci, w tym z przepisami o zwalczaniu wykorzystywania seksualnego dzieci. Materiały przedstawiające wykorzystywanie seksualne dzieci zgłaszamy właściwym organom ścigania.</p>
    <p>Niezależnie od zgłoszenia nam, takie materiały można zgłosić bezpośrednio:</p>
    <ul>
        <li>Policji — numer alarmowy <strong>112</strong>;</li>
        <li>zespołowi <strong>Dyżurnet.pl</strong> (NASK), punktowi kontaktowemu do zgłaszania nielegalnych treści w internecie — <a href="https://dyzurnet.pl" rel="noopener">dyzurnet.pl</a>.</li>
    </ul>

    <h2>Osoba kontaktowa</h2>
    <p>Osobą odpowiedzialną za stosowanie niniejszych standardów jest twórca aplikacji „Ja i Ty". Kontakt: <a href="mailto:kontakt@jaity.app">kontakt@jaity.app</a>.</p>

