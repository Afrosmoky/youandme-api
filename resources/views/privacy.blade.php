    <h1>Polityka prywatności</h1>
    <p class="upd">Ostatnia aktualizacja: 12 sierpnia 2026</p>

    <p>Aplikacja „Ja i Ty" to gra dla par. Traktujemy Wasze dane — a zwłaszcza to, co piszecie sobie nawzajem — poważnie. Ta polityka wyjaśnia, jakie dane zbieramy, po co, komu je powierzamy i jakie masz prawa.</p>

    <h2>Kto jest administratorem</h2>
    <p>Administratorem danych jest twórca aplikacji „Ja i Ty". W sprawach dotyczących prywatności i danych osobowych skontaktuj się z nami pod adresem <a href="mailto:kontakt@jaity.app">kontakt@jaity.app</a>.</p>

    <h2>Jakie dane zbieramy</h2>
    <ul>
        <li><strong>Dane konta:</strong> adres e-mail, nick, hasło (przechowywane wyłącznie w postaci zahaszowanej — nie znamy Twojego hasła), strefa czasowa, język, opcjonalnie nick osoby polecającej.</li>
        <li><strong>Treści, które tworzycie:</strong> odpowiedzi na pytania i zapisane wspomnienia. Mogą być osobiste i intymne — dlatego są dostępne wyłącznie w ramach Waszego konta.</li>
        <li><strong>Dane techniczne:</strong> token urządzenia do powiadomień (push), raporty o awariach aplikacji oraz podstawowe logi serwera (m.in. adres IP, czas żądania).</li>
        <li><strong>Logowanie zewnętrzne:</strong> jeśli logujesz się przez Google lub Apple, otrzymujemy z tego konta podstawowe dane identyfikacyjne (adres e-mail, identyfikator konta).</li>
    </ul>

    <h2>Po co przetwarzamy dane i na jakiej podstawie</h2>
    <ul>
        <li><strong>Świadczenie usługi</strong> (utworzenie konta, gra, zapisywanie wspomnień) — wykonanie umowy o świadczenie usług (art. 6 ust. 1 lit. b RODO).</li>
        <li><strong>Wysyłka e-maili</strong> (weryfikacja adresu, reset hasła) — niezbędna do korzystania z konta.</li>
        <li><strong>Powiadomienia push</strong> (przypomnienia, karta dnia) — na podstawie zgody wyrażonej w ustawieniach urządzenia.</li>
        <li><strong>Diagnostyka i stabilność</strong> (raporty awarii, logi) — nasz uzasadniony interes polegający na utrzymaniu poprawnego działania aplikacji (art. 6 ust. 1 lit. f RODO).</li>
    </ul>

    <h2>Raporty awarii a Wasze treści</h2>
    <p>Do wykrywania błędów używamy narzędzia Sentry. <strong>Raporty awarii nie zawierają treści Waszych odpowiedzi ani wspomnień</strong> — te dane są usuwane z raportu, zanim opuści urządzenie. Sentry widzi jedynie, że coś się zepsuło, gdzie i w której wersji aplikacji.</p>

    <h2>Komu powierzamy dane</h2>
    <p>Korzystamy z zaufanych dostawców, którzy przetwarzają dane wyłącznie na nasze polecenie i w zakresie niezbędnym do działania aplikacji:</p>
    <ul>
        <li><strong>Dostawca serwera (VPS)</strong> — hosting aplikacji i bazy danych.</li>
        <li><strong>Zoho</strong> — dostarczanie wiadomości e-mail.</li>
        <li><strong>Sentry</strong> — raportowanie awarii (przetwarzanie w regionie Unii Europejskiej).</li>
        <li><strong>Google / Firebase</strong> — powiadomienia push oraz logowanie przez Google.</li>
        <li><strong>Apple</strong> — logowanie przez Apple (jeśli z niego korzystasz).</li>
    </ul>
    <p>Nie sprzedajemy Waszych danych i nie udostępniamy ich w celach reklamowych.</p>

    <h2>Jak długo przechowujemy dane</h2>
    <p>Dane konta i Wasze treści przechowujemy tak długo, jak istnieje konto. Po usunięciu konta usuwamy powiązane z nim dane w rozsądnym terminie (z zastrzeżeniem danych, które musimy zachować z przyczyn prawnych lub bezpieczeństwa). Logi i raporty awarii przechowujemy przez ograniczony czas.</p>

    <h2>Twoje prawa</h2>
    <p>Przysługuje Ci prawo do: dostępu do swoich danych, ich sprostowania, usunięcia, ograniczenia przetwarzania, przenoszenia oraz wniesienia sprzeciwu. Masz też prawo wniesienia skargi do organu nadzorczego (w Polsce: Prezes Urzędu Ochrony Danych Osobowych).</p>
    <p>Aby skorzystać z tych praw lub usunąć konto, napisz do nas: <a href="mailto:kontakt@jaity.app">kontakt@jaity.app</a>.</p>

    <h2>Bezpieczeństwo</h2>
    <p>Połączenie z aplikacją jest szyfrowane (HTTPS/TLS). Hasła przechowujemy wyłącznie w postaci zahaszowanej, a token dostępu na urządzeniu — w bezpiecznym magazynie systemowym.</p>

    <h2>Dla kogo jest aplikacja</h2>
    <p>„Ja i Ty" jest przeznaczona dla osób pełnoletnich (18+). Nie kierujemy usługi do dzieci i świadomie nie zbieramy ich danych.</p>

    <h2>Zmiany polityki</h2>
    <p>Możemy aktualizować tę politykę wraz z rozwojem aplikacji. Data ostatniej aktualizacji znajduje się na górze strony. O istotnych zmianach poinformujemy w aplikacji lub mailem.</p>

    <h2>Kontakt</h2>
    <p>W każdej sprawie dotyczącej prywatności: <a href="mailto:kontakt@jaity.app">kontakt@jaity.app</a>.</p>

