    <h1>Kontakt i pomoc</h1>
    <p class="upd">Aplikacja „Ja i Ty"</p>

    <p>Piszcie do nas, gdy coś nie działa, czegoś brakuje albo chcecie o coś zapytać. Odpowiadamy osobiście — za aplikacją stoją dwie osoby, nie dział obsługi.</p>

    <a class="mail" href="mailto:kontakt@jaity.app">kontakt@jaity.app</a>

    <p>Odpowiadamy zwykle w ciągu dwóch dni roboczych. Jeśli zgłaszacie błąd, napiszcie, z jakiego telefonu korzystacie i co dokładnie się stało — to zwykle skraca sprawę o kilka wiadomości.</p>

    <h2>Najczęstsze sprawy</h2>

    <p><strong>Nie pamiętam hasła.</strong> Na ekranie logowania wybierz „Nie pamiętam hasła" i podaj adres e-mail przypisany do konta. Jeśli konto zakładaliście przez Google albo Apple, logujcie się tym samym sposobem co poprzednio — hasła wtedy nie ma.</p>

    <p><strong>Chcemy usunąć konto.</strong> Można to zrobić w aplikacji: <strong>Profil → Usuń konto</strong>. Jeśli nie macie dostępu do aplikacji, wszystko opisaliśmy na stronie <a href="/delete-account">usuwania konta</a>.</p>

    <p><strong>Gramy we dwoje na jednym telefonie.</strong> Tak to działa dzisiaj — jedno wspólne konto dla pary i jedno urządzenie, które sobie podajecie. Gra na dwóch telefonach jednocześnie jeszcze nie jest gotowa.</p>

    <p><strong>Karty się skończyły.</strong> Po zagraniu całej talii możecie rozdać ją od nowa — przycisk „Zagrajcie od nowa" na ekranie końca gry. Postęp na mapie zostaje nietknięty.</p>

    <h2>Treści w aplikacji</h2>
    <p>Jeśli uważacie, że któreś pytanie jest nie na miejscu, napiszcie nam które i dlaczego. Czytamy każdą taką wiadomość — talia powstaje po to, żeby rozmawiało się dobrze, a nie niezręcznie.</p>

